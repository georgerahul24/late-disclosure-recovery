"""Turn results/*.json (from scripts/summarize_runs.py) into LaTeX tables.

    python scripts/make_tables.py --main results/main_v1.json [--detectors results/detector_eval_v1.json] \
        --out paper/sections/results_tables.tex

Every number in the paper's results tables comes from here. Never edit the
generated .tex by hand; re-run this script.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ORDER = ["book_only", "rule_gate", "plain", "safety", "plain_label", "dsc", "recheck", "hybrid",
         "recheck_no_detector", "recheck_detector_tool", "recheck_no_retrieval", "recheck_full_record",
         "recheck_no_ledger", "recheck_no_readback", "recheck_single_pass"]
NAMES = {"book_only": "Book-only", "rule_gate": "Rule gate", "plain": "Plain", "safety": "Safety prompt",
         "plain_label": "Plain + Label", "dsc": "DSC (no LLM)", "recheck": r"\recheck{}", "hybrid": "Hybrid",
         "recheck_no_detector": r"\quad $-$ detector", "recheck_detector_tool": r"\quad detector as tool",
         "recheck_no_retrieval": r"\quad $-$ retrieval", "recheck_full_record": r"\quad full record",
         "recheck_no_ledger": r"\quad $-$ ledger", "recheck_no_readback": r"\quad $-$ read-back",
         "recheck_single_pass": r"\quad single-pass"}


def p(x, d=1):
    return "--" if x is None else f"{100 * x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--main", required=True)
    ap.add_argument("--detectors")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    J = json.loads(Path(args.main).read_text())
    T = [f"% Generated by scripts/make_tables.py from {args.main}. Do not edit by hand.", ""]
    core = J["core"]
    rows = [c for c in ORDER if c in core] + sorted(c for c in core if c not in ORDER and "oracle" not in c
                                                     and "tfidf" not in c and "keyword" not in c)
    T += [r"\begin{table*}[t]\centering\small",
          r"\begin{tabular}{lrrrrrrrr}\toprule",
          r"Condition & Policy unsafe [95\% CI] & Strict & Lenient & T1 & MID & POST & Completion & Contrast \\ \midrule"]
    for c in rows:
        r = core[c]
        pol = r["policy"]
        t = r["timing_policy"]
        T.append(f"{NAMES.get(c, c.replace('_', r'\_'))} & {p(pol[0])} [{p(pol[1])}, {p(pol[2])}] & {p(r['strict'][0])} & "
                 f"{p(r['lenient'])} & {p(t['T1'])} & {p(t['MID'])} & {p(t['POST'])} & {p(r['completion'])} & {p(r['contrast'])} \\\\")
    T += [r"\bottomrule\end{tabular}",
          r"\caption{Core episodes on the evaluation set (own symptom, volunteered, no tool fault). Unsafe rates are \% of red-flag "
          r"episodes; completion is \% of routine episodes; contrast is the share of matched pairs where both sides are handled "
          r"correctly. T1/MID/POST are policy-unsafe rates by disclosure time. Means are over scenarios (timings, phrasings and seeds averaged first).}",
          r"\label{tab:main}\end{table*}", ""]
    # stages
    T += [r"\begin{table}[t]\centering\small", r"\begin{tabular}{lrrrrr}\toprule",
          r"Condition & 1 Detect & 2 Context & 3 Not revised & 4 Repair failed & 5 Not escalated \\ \midrule"]
    for c in rows:
        r = core[c]
        n = r["n_fail"]
        if not n:
            continue
        sc = r["stage_counts"]
        T.append(f"{NAMES.get(c, c.replace('_', r'\_'))} & " + " & ".join(f"{100 * sc[k] / n:.0f}" for k in "12345") + r" \\")
    T += [r"\bottomrule\end{tabular}", r"\caption{Share (\%) of policy-unsafe red-flag episodes by the first failed stage.}",
          r"\label{tab:stages}\end{table}", ""]
    # tests
    T += [r"\begin{table}[t]\centering\small", r"\begin{tabular}{llrrr}\toprule",
          r"Test & A $-$ B & Diff. [95\% CI] & $p$ & $p_{\mathrm{Holm}}$ \\ \midrule"]
    for t in J["tests"]["policy"]:
        T.append(f"{t['name']} & {NAMES.get(t['a'], t['a'])} $-$ {NAMES.get(t['b'], t['b'])} & "
                 f"{100 * t['diff']:.1f} [{100 * t['lo']:.1f}, {100 * t['hi']:.1f}] & {t['p']:.3f} & {t['p_holm']:.3f} \\\\")
    for c, h in J.get("h1", {}).items():
        T.append(f"H1 ({NAMES.get(c, c)}) & POST $-$ T1 (strict) & {100 * h['diff']:.1f} [{100 * h['lo']:.1f}, {100 * h['hi']:.1f}] & {h['p']:.3f} & -- \\\\")
    if J.get("tost"):
        t = J["tost"]
        T.append(f"TOST & \\recheck{{}} vs DSC & 90\\% CI [{100 * t['lo90']:.1f}, {100 * t['hi90']:.1f}] & "
                 f"\\multicolumn{{2}}{{r}}{{{'equivalent' if t['equivalent'] else 'not equivalent'}}} \\\\")
    T += [r"\bottomrule\end{tabular}", r"\caption{Paired scenario-level comparisons on policy-unsafe rate (percentage points). "
          r"Bootstrap $p$-values; Holm correction over the five confirmatory tests.}", r"\label{tab:tests}\end{table}", ""]
    if args.detectors and Path(args.detectors).exists():
        D = json.loads(Path(args.detectors).read_text())
        T += [r"\begin{table}[t]\centering\small", r"\begin{tabular}{llrrrr}\toprule",
              r"Detector & Text & Sens. & Spec. & PPV & Macro-F1 \\ \midrule"]
        for r in D:
            T.append(f"{r['detector'].replace('_', r'\_')} & {r['variant']} & {p(r['sensitivity'])} & {p(r['specificity'])} & "
                     f"{p(r['ppv'])} & {p(r['macro_f1'])} \\\\")
        T += [r"\bottomrule\end{tabular}", r"\caption{Detectors on the evaluation text (never used for training). "
              r"Sensitivity is for any red flag versus benign.}", r"\label{tab:detectors}\end{table}", ""]
    Path(args.out).write_text("\n".join(T) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
